#!/usr/bin/env python3
"""Generate the in-game NPC deck table (gwai_npc_decks_data.ws) from sim/gwentsim/npc_balance.py.

For every native NPC deck variant (deck name and native difficulty) it writes:
- Strong: the card indices of strong_deck;
- Adaptive: balanced_steps, the first step in full, then each step as changes from the previous
  one ("-i" leaves the deck, "+i" joins it), each with the strength the builder checked; one
  such list per hero variant, separated by "#" (the game picks one per match).
The game picks the first Adaptive step whose strength reaches the target, as balanced_deck does.
Card indices are turned into card names in the game with GetGwentCardByIndex.

Builds a project artifact only; reads the local vanilla XML (not redistributed).
"""
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'sim'))

from evaluate_pool import XML, setup  # noqa: E402
from blunder_hunter import card_names  # noqa: E402
from gwentsim.native_decks import NativeDecks  # noqa: E402
from gwentsim.npc_balance import HERO_VARIANTS, balanced_steps, strong_deck  # noqa: E402

OUT = ROOT / 'mod/settings/modGwentAISettings/content/scripts/local/gwai_npc_decks_data.ws'


def delta(previous, current):
    removed = Counter(previous) - Counter(current)
    added = Counter(current) - Counter(previous)
    return ['-%d' % i for i in sorted(removed.elements())] + ['+%d' % i for i in sorted(added.elements())]


def table():
    match = setup()['match']
    templates, names = match.templates, card_names()
    native = NativeDecks(XML, templates)
    rows = []
    for name in native.npc_names():
        for variant in sorted({int(d.attrib['difficulty']) for d in native.collections[name].findall('deck')}):
            deck = native.build(name, variant, repaired=True)
            choices = []
            for hero_variant in range(HERO_VARIANTS):     # Adaptive heroes: one variant per match
                adaptive, previous = [], None
                for strength, cards in balanced_steps(templates, deck, names, hero_variant):
                    body = cards if previous is None else delta(previous, cards)
                    adaptive.append('%d:%s' % (strength, ','.join(str(c) for c in body)))
                    previous = cards
                choices.append('|'.join(adaptive))
            rows.append(('%s:%d' % (name, variant), ','.join(str(c) for c in strong_deck(templates, deck, names)),
                         '#'.join(choices)))
    return rows


def main():
    rows = table()
    # One small function per deck variant. A build with the whole table in one function compiled
    # but the game closed while loading (2026-10-11); its size is the suspected cause.
    lines = ['// Generated by tools/build_npc_decks.py from sim/gwentsim/npc_balance.py. Do not edit by hand.',
             '// Key "<native deck name>:<native difficulty>". Strong: card indices. Adaptive: steps',
             '// "<strength>:<cards>", the first in full, then "-index"/"+index" changes; hero variants',
             '// are separated by "#" and the game picks one per match.',
             'function GwaiNpcDeckTable(key : string, out strong : string, out adaptive : string) : bool',
             '{']
    for n, (key, strong, adaptive) in enumerate(rows):
        lines += ['    if (key == "%s") { GwaiNpcDeck%d(strong, adaptive); return true; }' % (key, n)]
    lines += ['    return false;', '}', '']
    for n, (key, strong, adaptive) in enumerate(rows):
        lines += ['function GwaiNpcDeck%d(out strong : string, out adaptive : string)' % n, '{',
                  '    strong = "%s";' % strong, '    adaptive = "%s";' % adaptive, '}', '']
    OUT.write_text('\n'.join(lines))
    print('%d deck variants -> %s (%d bytes)' % (len(rows), OUT.relative_to(ROOT), OUT.stat().st_size))


if __name__ == '__main__':
    main()
